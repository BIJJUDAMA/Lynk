// Generate a docker-compose override that caps the whole server stack to an
// arbitrary total RAM budget (in MiB), scaling every container from one number.
//
// Usage:
//   node tests/load/ramcap.js 6144 > docker-compose.ramcap.yml
//   node tests/load/ramcap.js 4096
//
// Any positive integer works (4096, 5120, 6144, 237568, ...). The Postgres
// shared_buffers is set to the larger of 128 MiB and 1/8 of the budget (a
// sensible cache share, since Postgres owns the hot data); the remaining
// containers take fixed fractional shares and the fractions sum to 1.0, so the
// stack always fits under the budget.
// 100% pure ASCII

'use strict';

const ram = parseInt(process.argv[2], 10);
if (!Number.isFinite(ram) || ram < 1024) {
  console.error('usage: node tests/load/ramcap.js <TOTAL_MiB>   (minimum 1024)');
  process.exit(2);
}

// Fractional shares of the total budget. They sum to 1.0.
const SHARES = {
  postgres: 0.38,
  api: 0.13,
  supertokens: 0.13,
  'ai-api': 0.08,
  redis: 0.08,
  minio: 0.08,
  'ai-worker': 0.05,
  pgbouncer: 0.035,
  gateway: 0.035,
};

function mb(fraction) {
  return Math.max(64, Math.floor(ram * fraction)) + 'm';
}

// Postgres shared_buffers: a quarter of its own share, floor 128 MiB.
const pgShare = Math.floor(ram * SHARES.postgres);
const sharedBuffers = Math.max(128, Math.floor(pgShare / 4));
// GOMEMLIMIT for the Go API: 80% of its share, so GC keeps it under the cap.
const apiShare = Math.floor(ram * SHARES.api);
const goMemLimit = Math.floor(apiShare * 0.8);

const yaml = `# GENERATED by tests/load/ramcap.js ${ram} - do not edit by hand.
# Whole server stack capped to ${ram} MiB total (swap disabled per container).
# Regenerate: node tests/load/ramcap.js ${ram} > docker-compose.ramcap.yml
services:
  postgres:
    command: >
      postgres
      -c shared_buffers=${sharedBuffers}MB
      -c effective_cache_size=${sharedBuffers}MB
      -c work_mem=8MB
      -c maintenance_work_mem=128MB
      -c checkpoint_completion_target=0.9
      -c wal_buffers=16MB
      -c random_page_cost=1.1
      -c effective_io_concurrency=200
      -c max_connections=200
    mem_limit: ${mb(SHARES.postgres)}
    memswap_limit: ${mb(SHARES.postgres)}

  supertokens:
    mem_limit: ${mb(SHARES.supertokens)}
    memswap_limit: ${mb(SHARES.supertokens)}

  minio:
    mem_limit: ${mb(SHARES.minio)}
    memswap_limit: ${mb(SHARES.minio)}

  redis:
    mem_limit: ${mb(SHARES.redis)}
    memswap_limit: ${mb(SHARES.redis)}

  pgbouncer:
    mem_limit: ${mb(SHARES.pgbouncer)}
    memswap_limit: ${mb(SHARES.pgbouncer)}

  api:
    environment:
      GOMEMLIMIT: "${goMemLimit}MiB"
      GOGC: "100"
    mem_limit: ${mb(SHARES.api)}
    memswap_limit: ${mb(SHARES.api)}

  gateway:
    mem_limit: ${mb(SHARES.gateway)}
    memswap_limit: ${mb(SHARES.gateway)}

  ai-api:
    mem_limit: ${mb(SHARES['ai-api'])}
    memswap_limit: ${mb(SHARES['ai-api'])}

  ai-worker:
    mem_limit: ${mb(SHARES['ai-worker'])}
    memswap_limit: ${mb(SHARES['ai-worker'])}
`;

process.stdout.write(yaml);
const total = Object.values(SHARES).reduce((a, b) => a + b, 0);
console.error(`[ramcap] budget=${ram} MiB, shares sum=${total.toFixed(3)}, postgres shared_buffers=${sharedBuffers}MB, GOMEMLIMIT=${goMemLimit}MiB`);
